CREATE EXTENSION IF NOT EXISTS vector;

ALTER TABLE signup
  ADD COLUMN IF NOT EXISTS password_hash TEXT;

CREATE TABLE IF NOT EXISTS categories (
  category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tags (
  tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS post_categories (
  post_id INTEGER NOT NULL REFERENCES posts (post_id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES categories (category_id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, category_id)
);

CREATE TABLE IF NOT EXISTS post_tags (
  post_id INTEGER NOT NULL REFERENCES posts (post_id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES tags (tag_id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, tag_id)
);

CREATE INDEX IF NOT EXISTS post_categories_category_id_idx
  ON post_categories (category_id, post_id);

CREATE INDEX IF NOT EXISTS post_tags_tag_id_idx
  ON post_tags (tag_id, post_id);

CREATE TABLE IF NOT EXISTS post_embeddings (
  post_id INTEGER PRIMARY KEY REFERENCES posts (post_id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  embedding VECTOR(1536) NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS post_embeddings_embedding_idx
  ON post_embeddings USING hnsw (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS embedding_jobs (
  post_id INTEGER PRIMARY KEY REFERENCES posts (post_id) ON DELETE CASCADE,
  attempts INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'failed')),
  available_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  queued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processing_since TIMESTAMPTZ,
  last_error TEXT
);
